export const language = () => currentLanguage;
export const locale = () => currentLanguage === 'ru' ? 'ru-RU' : 'en-US';
export function setLanguage(value) { currentLanguage = value === 'ru' ? 'ru' : 'en'; }
export function t(key, ...values) {
  const text = currentLanguage === 'ru' ? key : messages[key] ?? key;
  return String(text).replace(/\{(\d+)\}/g, (match, index) => values[index] === undefined ? match : String(values[index]));
}
export function applyTranslations(document) {
  document.documentElement.lang = currentLanguage;
  for (const element of document.querySelectorAll('[data-i18n]')) element.textContent = t(element.dataset.i18n);
  for (const attribute of ['title', 'aria-label', 'placeholder']) {
    for (const element of document.querySelectorAll('[data-i18n-' + attribute + ']')) element.setAttribute(attribute, t(element.getAttribute('data-i18n-' + attribute)));
  }
}
// Only service-owned fields use this exact/template mapping. Unknown errors stay intact.
export function localizeService(value) {
  if (typeof value !== 'string') return value ?? '';
  if (Object.hasOwn(messages, value)) return t(value);
  const sourceKey = Object.keys(messages).find(key => messages[key] === value);
  if (sourceKey) return t(sourceKey);
  for (const [pattern, translated] of serviceTemplates) {
    const match = value.match(pattern);
    if (match) {
      const values = match.slice(1);
      // Only the cause field of known service wrappers may contain another service message.
      // Paths, names, reference targets and recovery locations remain opaque.
      if (translated.startsWith('Не удалось прочитать ') || translated.startsWith('Не удалось проверить Git ')) values[values.length - 1] = localizeService(values[values.length - 1]);
      return t(translated, ...values);
    }
  }
  return value;
}
