import test from 'node:test';
import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { readFile } from 'node:fs/promises';
import { undo, redo } from '@codemirror/commands';

test('the editor shows grouped skills, filters them and edits the selected Markdown', async () => {
  const html = await readFile(new URL('../ui/index.html', import.meta.url), 'utf8');
  const dom = new JSDOM(html, { pretendToBeVisual: true });
  const win = dom.window;
  for (const key of ['window','Window','Option','document','navigator','MutationObserver','HTMLElement','Element','Node','getComputedStyle','requestAnimationFrame','cancelAnimationFrame']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? win : typeof win[key] === 'function' && ['getComputedStyle','requestAnimationFrame','cancelAnimationFrame'].includes(key) ? win[key].bind(win) : win[key] });
  win.Range.prototype.getClientRects = () => [];
  win.Range.prototype.getBoundingClientRect = () => ({ x:0,y:0,left:0,top:0,right:0,bottom:0,width:0,height:0 });
  const { mountStudio } = await import('../ui/view.mjs');
  let disk = '# Before';
  const call = async (name, args) => {
    if (name === 'open') return { projects: [{ id:'p', name:'Project' }, { id:'q', name:'Second project', roots:['/projects/second'] }], selectedProjectId:'p', warnings:[] };
    if (name === 'list') return { skills:[{id:'g',name:'Global',scope:'global',source:'Personal',agentSkill:{lockfile:'/home/skills.lock.toml',source:'team/skills'},git:{repository:'/repo',trackedPath:'skills/global/SKILL.md'}},{id:'l',name:'Local',scope:'local',source:'Project',git:{repository:'/repo',trackedPath:'skills/local/SKILL.md'}},...(args.includeSystem?[{id:'sys',name:'Builtin',scope:'global',source:'Системные',readOnly:true,system:true}]:[]),...(args.includePlugins?[{id:'pa',name:'Packaged A',scope:'plugin',source:'Alpha',readOnly:true,plugin:{id:'one',name:'Alpha'}},{id:'pb',name:'Packaged B',scope:'plugin',source:'Beta',readOnly:true,plugin:{id:'two',name:'Beta'}}]:[])], warnings:[] };
    if (name === 'read') return {id:args.id,name:args.id==='g'?'Global':'Local',scope:'global',path:'/skills/SKILL.md',content:disk,revision:'r1',readOnly:false};
    if (name === 'update_preferences') return args;
    if (name === 'select_project') return {selectedProjectId:args.projectId};
    if (name === 'save') {disk=args.content;return {revision:'r2'};}
  };
  const ui = mountStudio({ call });
  try {
    await ui.controller.initialize();
    assert.equal(win.document.querySelector('#hide-system-skills').checked,true);
    assert.match(win.document.querySelector('#skills').textContent, /Локальные/);
    assert.match(win.document.querySelector('#skills').textContent, /Глобальные/);
    const globalRow = [...win.document.querySelectorAll('.skill')].find(e => e.querySelector('.skill-name').textContent === 'Global');
    const localRow = [...win.document.querySelectorAll('.skill')].find(e => e.querySelector('.skill-name').textContent === 'Local');
    const modes = win.document.querySelector('#document-modes');
    const editButton = win.document.querySelector('#mode-edit');
    const viewButton = win.document.querySelector('#mode-view');
    const diffButton = win.document.querySelector('#mode-diff');
    assert.ok(modes, 'the mode switch is available before Save');
    assert.equal(modes.nextElementSibling.id, 'save');
    assert.equal(win.document.querySelector('#reload'), null);
    assert.deepEqual([...modes.querySelectorAll('[role=tab]')].map(e => e.textContent), ['VIEW', 'EDIT', 'DIFF']);
    assert.equal(diffButton.disabled, true);
    assert.deepEqual([...globalRow.querySelectorAll('.skill-badge')].map(e => e.textContent), ['AgentSkill Skills', 'Git']);
    assert.deepEqual([...localRow.querySelectorAll('.skill-badge')].map(e => e.textContent), ['Git']);
    assert.match(globalRow.querySelector('.badge-agentSkill').title, /skills.lock.toml/);
    await ui.controller.open('g');
    assert.equal(win.document.querySelector('#title').textContent, 'Global');
    assert.equal(ui.editor.state.doc.toString(), '# Before');
    assert.equal(diffButton.disabled, false);
    assert.equal(viewButton.getAttribute('aria-selected'),'true');
    assert.equal(win.document.querySelector('#markdown-view').hidden,false);
    assert.equal(win.document.querySelector('#editor').hidden,true);
    assert.equal(win.document.querySelector('#location-actions').hidden,false);
    editButton.click();
    ui.editor.dispatch({ changes: { from:0,to:ui.editor.state.doc.length,insert:'# After' } });
    assert.equal(win.document.querySelector('#save').disabled, false);
    const selection = ui.editor.state.selection.main.head;
    viewButton.click();
    assert.equal(viewButton.getAttribute('aria-selected'), 'true');
    assert.equal(win.document.querySelector('#editor').hidden, true);
    const preview = win.document.querySelector('#markdown-view');
    assert.equal(preview.hidden, false);
    assert.equal(preview.querySelector('h1').textContent, 'After', 'VIEW renders unsaved Markdown');
    assert.equal(preview.querySelector('[contenteditable=true],textarea,input'), null);
    diffButton.click();
    assert.equal(diffButton.getAttribute('aria-selected'), 'true');
    assert.equal(preview.hidden, true);
    assert.equal(win.document.querySelector('#editor').hidden, true);
    assert.equal(win.document.querySelector('#diff-view').hidden, false);
    assert.equal(win.document.querySelector('.diff-remove').textContent, '-# Before');
    assert.equal(win.document.querySelector('.diff-add').textContent, '+# After');
    editButton.click();
    assert.equal(win.document.querySelector('#editor').hidden, false);
    assert.equal(ui.editor.state.doc.toString(), '# After');
    assert.equal(ui.editor.state.selection.main.head, selection);
    assert.equal(ui.controller.dirty, true);
    assert.equal(undo(ui.editor), true);
    assert.equal(ui.editor.state.doc.toString(), '# Before');
    assert.equal(redo(ui.editor), true);
    assert.equal(ui.editor.state.doc.toString(), '# After');
    viewButton.click();
    preview.scrollTop = 120;
    ui.applyTheme('light'); ui.controller.emit();
    assert.equal(preview.scrollTop, 120, 'routine renders preserve preview scroll');
    assert.equal(win.document.querySelectorAll('#document-modes [aria-selected=true]').length, 1);
    viewButton.dispatchEvent(new win.KeyboardEvent('keydown', {key:'ArrowRight',bubbles:true,cancelable:true}));
    assert.equal(editButton.getAttribute('aria-selected'),'true');
    editButton.dispatchEvent(new win.KeyboardEvent('keydown', {key:'ArrowRight',bubbles:true,cancelable:true}));
    assert.equal(diffButton.getAttribute('aria-selected'), 'true');
    assert.equal(win.document.activeElement, diffButton);
    assert.equal(diffButton.tabIndex, 0);
    assert.equal(viewButton.tabIndex, -1);
    diffButton.dispatchEvent(new win.KeyboardEvent('keydown', {key:'Home',bubbles:true,cancelable:true}));
    assert.equal(viewButton.getAttribute('aria-selected'), 'true');
    diffButton.click();
    await ui.controller.save();
    assert.equal(disk, '# After');
    assert.equal(win.document.querySelector('#save').disabled, true);
    assert.equal(win.document.querySelector('#diff-view').hidden, false);
    assert.equal(win.document.querySelectorAll('.diff-add, .diff-remove').length, 0);
    assert.match(win.document.querySelector('#diff-view').textContent, /Изменений нет/);
    win.document.querySelector('#project').click();
    const projectSearch = win.document.querySelector('#project-filter');
    projectSearch.value = 'Second'; projectSearch.dispatchEvent(new win.Event('input'));
    projectSearch.dispatchEvent(new win.KeyboardEvent('keydown', {key:'Enter',bubbles:true,cancelable:true}));
    await new Promise(resolve => setImmediate(resolve));
    assert.equal(ui.controller.state.projectId, 'q');
    assert.match(win.document.querySelector('#project').textContent, /Second project/);
    assert.equal(win.document.querySelector('#project-menu').hidden, true);
    assert.equal(win.document.querySelector('#diff-view').hidden, true);
    const search = win.document.querySelector('#search'); search.value='Local'; search.dispatchEvent(new win.Event('input'));
    assert.deepEqual([...win.document.querySelectorAll('.skill-name')].map(e=>e.textContent), ['Local']);
    search.value = 'agentSkill'; search.dispatchEvent(new win.Event('input'));
    assert.deepEqual([...win.document.querySelectorAll('.skill-name')].map(e=>e.textContent), ['Global']);
    search.value='';search.dispatchEvent(new win.Event('input'));
    const toggle=win.document.querySelector('#hide-system-skills');
    toggle.checked=false;toggle.dispatchEvent(new win.Event('change'));
    await new Promise(resolve=>setImmediate(resolve));
    assert.deepEqual([...win.document.querySelectorAll('.section-title')].map(e=>e.textContent),['Локальные','Глобальные','Alpha','Beta']);
    const globalSection=win.document.querySelector('[data-section="global"]');
    assert.equal(globalSection.querySelectorAll('.skill').length,2);
    await ui.controller.open('g');
    editButton.click();
    await ui.controller.open('l');
    assert.equal(viewButton.getAttribute('aria-selected'),'true','each skill opens in VIEW');
    await ui.controller.open('g');
    win.document.querySelector('[data-section="global"] .section-heading').click();
    await new Promise(resolve=>setImmediate(resolve));
    const collapsed=win.document.querySelector('[data-section="global"]');
    assert.equal(collapsed.querySelector('.section-items').hidden,true);
    assert.equal(collapsed.querySelector('.section-heading').getAttribute('aria-expanded'),'false');
    assert.equal(ui.editor.state.doc.toString(),'# After');
    assert.equal(win.document.querySelector('[data-section="plugin:one"] .section-items').hidden,false);
    toggle.checked=true;toggle.dispatchEvent(new win.Event('change'));
    await new Promise(resolve=>setImmediate(resolve));
    assert.ok(win.document.querySelector('[data-section="plugin:one"]'), 'system filter leaves plugins visible');
    const pluginToggle=win.document.querySelector('#hide-plugin-skills');pluginToggle.checked=true;pluginToggle.dispatchEvent(new win.Event('change'));
    await new Promise(resolve=>setImmediate(resolve));
    assert.equal(win.document.querySelector('[data-section="plugin:one"]'),null);

  } finally { ui.destroy(); dom.window.close(); }
});
