import test from 'node:test';
import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { mkdtemp, mkdir, readFile, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';
import { SkillStore } from '../src/store.mjs';
import { createServer } from '../src/server.mjs';

test('context-menu actions rename, copy, reveal, move and confirm deletion through the real MCP server', async () => {
  const root = await mkdtemp(join(tmpdir(), 'skills-studio-menu-ui-'));
  const home = join(root, 'home'), codexHome = join(home, '.codex'), project = join(root, 'project');
  const source = join(home, '.agents/skills/sample');
  await mkdir(join(source, 'assets'), { recursive:true }); await mkdir(codexHome, { recursive:true }); await mkdir(project, { recursive:true });
  await writeFile(join(source, 'SKILL.md'), '---\nname: Original\ndescription: Example\n---\n# Body\n');
  await writeFile(join(source, 'assets/fixture.txt'), 'Resource');
  await writeFile(join(codexHome, '.codex-global-state.json'), JSON.stringify({ 'local-projects':{ p:{name:'Project',rootPaths:[project]} } }));
  const enabled = new Map();
  const runtime = {snapshot:async()=>({data:[{skills:[join(source,'SKILL.md'),join(home,'.agents/skills/sample-copy/SKILL.md'),join(project,'.agents/skills/sample-copy/SKILL.md')].map(path=>({path,enabled:enabled.get(path)!==false}))}]}),setEnabled:async(path,value)=>enabled.set(path,value)};
  const store = new SkillStore({ home, codexHome, stateDir:join(root,'state'), runtime });
  const revealed = [];
  const server = createServer({ store, reveal:async path => { revealed.push(path); } });
  const client = new Client({ name:'menu-test',version:'1' });
  const [ct,st] = InMemoryTransport.createLinkedPair(); await server.connect(st); await client.connect(ct);
  const dom = new JSDOM(await readFile(new URL('../ui/index.html', import.meta.url), 'utf8'), { pretendToBeVisual:true });
  const win = dom.window, doc = win.document;
  for (const key of ['window','Window','Option','document','navigator','MutationObserver','HTMLElement','Element','Node','getComputedStyle','requestAnimationFrame','cancelAnimationFrame']) Object.defineProperty(globalThis, key, { configurable:true, value:key === 'window' ? win : typeof win[key] === 'function' && ['getComputedStyle','requestAnimationFrame','cancelAnimationFrame'].includes(key) ? win[key].bind(win) : win[key] });
  win.Range.prototype.getClientRects = () => [];
  win.Range.prototype.getBoundingClientRect = () => ({ x:0,y:0,left:0,top:0,right:0,bottom:0,width:0,height:0 });
  win.HTMLDialogElement.prototype.showModal = function () { this.open = true; };
  win.HTMLDialogElement.prototype.close = function (value) { this.returnValue = value || ''; this.open = false; this.dispatchEvent(new win.Event('close')); };
  const { mountStudio } = await import('../ui/view.mjs');
  const ui = mountStudio({ call:async (name,args={}) => {
    const result = await client.callTool({ name:'skills_studio.' + name, arguments:args });
    if (result.isError) throw Object.assign(new Error(result.structuredContent.message), {code:result.structuredContent.code});
    return result.structuredContent;
  } });
  const waitFor = async check => {
    const deadline = Date.now() + 3000;
    while (!check() && Date.now() < deadline) await new Promise(resolve => setTimeout(resolve, 10));
    assert.ok(check(), ui.controller.state.error?.message || 'Operation completed');
  };
  const menu = (name, action, rightClick = false) => {
    const row = [...doc.querySelectorAll('.skill-row')].find(row => row.querySelector('.skill-name').textContent === name);
    assert.ok(row, `Skill row ${name} exists`);
    if (rightClick) row.dispatchEvent(new win.MouseEvent('contextmenu', {bubbles:true,clientX:30,clientY:40,cancelable:true}));
    else row.querySelector('.skill-menu-trigger').click();
    doc.querySelector(`#skill-menu [data-action="${action}"]`).click();
  };
  try {
    await ui.controller.initialize(); await ui.controller.selectProject('p');
    menu('Original', 'rename', true);
    doc.querySelector('#skill-new-name').value = 'Renamed'; doc.querySelector('#skill-name-submit').click();
    await waitFor(() => ui.controller.state.current?.name === 'Renamed' && !ui.controller.state.busy);
    assert.match(await readFile(join(source,'SKILL.md'),'utf8'), /name: Renamed/);
    menu('Renamed', 'copy'); doc.querySelector('#skill-new-name').value = 'Copied'; doc.querySelector('#skill-name-submit').click();
    await waitFor(() => ui.controller.state.current?.name === 'Copied' && !ui.controller.state.busy);
    menu('Copied', 'move');
    await waitFor(() => ui.controller.state.current?.scope === 'local' && !ui.controller.state.busy);
    const localPath = ui.controller.state.current.path;
    assert.equal(await readFile(join(dirname(localPath),'assets/fixture.txt'),'utf8'), 'Resource');
    ui.editor.dispatch({changes:{from:ui.editor.state.doc.length,insert:'\nUnsaved\n'}});
    menu('Copied','disable');
    assert.equal(doc.querySelector('#unsaved').open,true);
    doc.querySelector('#cancel-switch').click();
    await new Promise(resolve=>setImmediate(resolve));
    assert.equal(ui.controller.dirty,true);
    assert.equal((await readFile(localPath,'utf8')).includes('Unsaved'),false);
    menu('Copied','disable'); doc.querySelector('#save-switch').click();
    await waitFor(()=>ui.controller.state.current?.availability?.status === 'disabled' && !ui.controller.state.busy);
    assert.equal(ui.controller.state.current.path,localPath);
    assert.match(await readFile(ui.controller.state.current.path,'utf8'),/Unsaved/);
    assert.equal(enabled.get(localPath),false);
    const search = doc.querySelector('#search'); search.value='выключен'; search.dispatchEvent(new win.Event('input'));
    assert.deepEqual([...doc.querySelectorAll('.skill-name')].map(e=>e.textContent),['Copied']);
    search.value=''; search.dispatchEvent(new win.Event('input'));
    menu('Copied','enable');
    await waitFor(()=>ui.controller.state.current?.disabled === false && !ui.controller.state.busy);
    assert.equal(ui.controller.state.current.path,localPath);
    assert.equal(doc.querySelector('.badge-disabled'),null);
    menu('Copied', 'reveal'); await waitFor(() => revealed.length === 1);
    assert.equal(revealed[0], localPath);
    menu('Copied', 'delete'); doc.querySelector('#delete-skill-cancel').click();
    assert.equal(await readFile(localPath,'utf8'), ui.controller.state.current.content);
    menu('Copied', 'delete'); doc.querySelector('#delete-skill-confirm').click();
    await waitFor(() => !ui.controller.state.skills.some(skill => skill.name === 'Copied') && !ui.controller.state.busy);
    assert.equal(ui.controller.state.current, null);
    await assert.rejects(readFile(localPath), {code:'ENOENT'});
    assert.equal(ui.controller.state.skills[0].name, 'Renamed');
  } finally { ui.destroy(); dom.window.close(); await client.close(); await server.close(); await rm(root,{recursive:true,force:true}); }
});
